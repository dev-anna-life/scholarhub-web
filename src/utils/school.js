export function getSchoolLogoUrl(school) {
  if (!school) return null
  const lower = school.toLowerCase().trim()
  if (knownSchoolLogos[lower]) return knownSchoolLogos[lower]
  for (const [key, url] of Object.entries(knownSchoolLogos)) {
    if (lower.includes(key) || key.includes(lower)) return url
  }
  return null
}

export function getSchoolAbbr(school) {
  if (!school) return '?'
  const lower = school.toLowerCase().trim()
  if (knownAbbreviations[lower]) return knownAbbreviations[lower]
  for (const [key, abbr] of Object.entries(knownAbbreviations)) {
    if (lower.includes(key) || key.includes(lower)) return abbr
  }
  const stopWords = new Set(['and', 'the', 'for', 'of', 'in', 'at', '&'])
  return school
    .split(/[\s,()]+/)
    .filter(w => w.length > 0 && !stopWords.has(w.toLowerCase()))
    .map(w => w[0].toUpperCase())
    .join('')
    .slice(0, 6) || school.slice(0, 4).toUpperCase()
}

export function stringToColor(school) {
  if (!school) return '#008751'
  const lower = school.toLowerCase().trim()
  if (schoolColors[lower]) return schoolColors[lower]
  let hash = 0
  for (let i = 0; i < lower.length; i++) hash = lower.charCodeAt(i) + ((hash << 5) - hash)
  const palette = ['#008751', '#FF9F1C', '#1F2A1F', '#e63946', '#457b9d', '#6a4c93', '#f4a261', '#2a9d8f']
  return palette[Math.abs(hash) % palette.length]
}
